'use strict';
const assert=require('node:assert/strict');
const C=require('./docs/character-geometry.js');
const CollisionWorld=require('./docs/collision-world.js');
const box=(x0,y0,x1,y1)=>[[x0,y0],[x1,y0],[x1,y1],[x0,y1]];
const actor=new C.Character('test-square',box(-5,-5,5,5),0);
const entry=(id,x,y,angle=0,shape=actor)=>({id,actor:shape,meta:{keep:true},body:{x,y,angle,sx:1,sy:1,bend:0,strain:0,bounce:0,edgeBends:shape.vertices.map(()=>0)}});
const world=new CollisionWorld([{id:'room',walls:[box(96,0,104,90),box(96,110,104,200)]}]);
let previous=[entry('door',80,100)];
for(let i=0;i<3;i++)previous=world.resolve(previous,[entry('door',120,100)]);
assert.equal(previous[0].body.x,120,'open doorway must remain passable');
previous=[entry('wall',80,50)];
for(let i=0;i<3;i++)previous=world.resolve(previous,[entry('wall',120,50)]);
assert(previous[0].body.x<=91.00001&&previous[0].collision.blocked);
assert(!C.penetrates(actor.outline(previous[0].body),box(96,0,104,90)));
const larger=new C.Character('larger',box(-10,-10,10,10),0),empty=new CollisionWorld();
previous=[entry('a',0,0,0,larger),entry('b',50,0,0,larger)];
for(let i=0;i<3;i++)previous=empty.resolve(previous,[entry('a',40,0,0,larger),entry('b',10,0,0,larger)]);
assert(!C.penetrates(larger.outline(previous[0].body),larger.outline(previous[1].body)));
assert(previous[0].body.x<previous[1].body.x,'opposing actors must not swap through one another');
const retained=empty.resolve(previous,[entry('a',40,0,0,larger)]);assert(retained[0].body.x>previous[0].body.x,'disappeared actor reservations must be removed');
const thin=new C.Character('thin',box(-20,-2,20,2),0),rotationWall=box(-30,14,30,64),rotating=new CollisionWorld([{id:'ceiling',walls:[rotationWall]}]);
const rotated=rotating.resolve([entry('r',0,0,0,thin)],[entry('r',0,0,Math.PI/2,thin)])[0];
assert(rotated.body.angle>0&&rotated.body.angle<Math.PI/2&&rotated.collision.blocked);
assert(!C.penetrates(thin.outline(rotated.body),rotationWall));
const spawned=empty.resolve([],[entry('one',0,0),entry('two',0,0)]);
assert.equal(spawned.length,2);assert(spawned[1].collision.spawnAdjusted);assert(!C.penetrates(actor.outline(spawned[0].body),actor.outline(spawned[1].body)));
const identical=box(0,0,10,10);assert(C.penetrates(identical,identical));assert(C.penetrates(identical,box(9,0,19,10)));assert(!C.penetrates(identical,box(10,0,20,10)));
const capped=empty.resolve([entry('cap',0,0)],[entry('cap',500,0)])[0];assert.equal(capped.body.x,64);assert(capped.collision.capped);assert(capped.meta.keep);
console.log('PASS collision world: doorway, wall sweep, reserved actors, disappearance, rotation, spawn, identical/collinear polygons, 64px cap.');
